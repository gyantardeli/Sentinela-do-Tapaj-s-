import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import ts from "typescript";

const cache = new Map();
function load(name) {
  const file = path.resolve(name);
  if (cache.has(file)) return cache.get(file);
  const exports = {}; cache.set(file, exports);
  const compiled = ts.transpileModule(fs.readFileSync(file, "utf8"), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
  new Function("require", "exports", compiled)(specifier => load(path.resolve(path.dirname(file), specifier + ".ts")), exports);
  return exports;
}
const { buildFireReplay, replayFrame, replayPoints, replayCsv, replayBoundary, EVENT_GAP_SECONDS } = load("lib/fire-replay.ts");
const { containsPoint } = load("lib/areas.ts");
const start = 1792300000, end = start + 86400;
const fire = (id, lat, lon, time, satellite = "NPP-375") => ({ id, lat, lon, time, satellite, frp: null, source: "INPE" });
const a = fire("a", -4.27, -55.99, start + 100);
const b = fire("b", -4.272, -55.992, start + 400);
const far = fire("far", -5.1, -56.4, start + 500);
const late = fire("late", -4.272, -55.992, b.time + EVENT_GAP_SECONDS + 1);
const future = fire("future", -4.273, -55.99, end + 1);
const replay = buildFireReplay([future, late, far, b, a, { ...a, frp: 10 }], start, end);
assert.equal(replay.detections.length, 4, "exact duplicate is removed, future observation is excluded");
assert.equal(replay.detections.find(f => f.id === "a").frp, 10, "complementary attributes survive deduplication");
assert.equal(replay.detections[0].eventId, replay.detections[1].eventId, "nearby observations associate sequentially");
assert.notEqual(replay.detections[0].eventId, replay.detections[2].eventId, "distant detection stays separate");
assert.notEqual(replay.detections[1].eventId, replay.detections[3].eventId, "more than six hours opens another query event");
assert.equal(new Set(replay.detections.map(f => f.detectionId)).size, 4);
assert.deepEqual(replay.times, [...new Set([start, a.time, b.time, far.time, late.time, end])]);
const before = replayFrame(replay, start);
assert.equal(before.visible.length, 0);
assert.equal(before.events.length, 0, "future event summaries must not leak into earlier frames");
const first = replayFrame(replay, b.time);
assert.equal(first.visible.length, 2);
assert.equal(first.events.length, 1);
assert.equal(first.events[0].lastAt, b.time);
const prefix = buildFireReplay([b, a, { ...a, frp: 10 }], start, end);
assert.deepEqual(first.events, replayFrame(prefix, b.time).events, "later observations cannot retroactively change the past");
assert.equal(replayFrame(replay, late.time, "all", true).visible.length, 1);
assert.equal(replayFrame(replay, end, first.events[0].id).visible.length, 2);
assert.deepEqual(buildFireReplay([late, b, far, a], start, end).detections.map(f => f.eventId), replay.detections.map(f => f.eventId), "input order does not alter grouping");
const simultaneous = buildFireReplay([a, fire("different-satellite", a.lat, a.lon, a.time, "AQUA_M-T")], start, end);
assert.equal(simultaneous.detections.length, 2, "different satellite observations remain inspectable");
assert.equal(replayPoints(first.visible, b.time).features[0].geometry.coordinates[0], a.lon, "GeoJSON longitude comes first");
const csv = replayCsv(first.visible, b.time);
assert.match(csv, /id_deteccao/); assert.match(csv, /grupo_estimado_recorte/); assert.ok(!csv.includes('"future"'));
const polygon = { id: "test", kind: "polygon", name: "Teste", radiusKm: 0, updatedAt: start, points: [{ lat: -4.3, lon: -56 }, { lat: -4.2, lon: -56 }, { lat: -4.2, lon: -55.9 }, { lat: -4.3, lon: -55.9 }] };
assert.equal(containsPoint(polygon, a), true); assert.equal(containsPoint(polygon, far), false);
const ring = replayBoundary({ id: "itb", name: "Itaituba", lat: a.lat, lon: a.lon }, 25).features[0].geometry.coordinates;
assert.equal(ring.length, 97); assert.ok(Math.abs(ring[0][0] - ring.at(-1)[0]) < 1e-9);
assert.equal(replayBoundary({ id: "itb", name: "Itaituba", lat: a.lat, lon: a.lon }, 25, polygon).features[0].geometry.coordinates.length, 5);
